function detectedLanguage(text) {
  if (Object.prototype.hasOwnProperty.call(COPY_EN, text)) return "es";
  if (Object.prototype.hasOwnProperty.call(COPY_ES, text)) return "en";
  if (/^(El pedido|Incidencia |Bienvenido\/a,|\d+ referencias? )/.test(text)) return "es";
  if (/^(Order |Support request |Welcome,|\d+ titles? )/.test(text)) return "en";
  return currentLanguage;
}

function translateFromLanguage(value, sourceLanguage, targetLanguage) {
  if (sourceLanguage === targetLanguage) return value;
  const targetDictionary = targetLanguage === "en" ? COPY_EN : COPY_ES;
  const previousLanguage = currentLanguage;
  currentLanguage = targetLanguage;
  const translated = targetDictionary[value] || translateText(value);
  currentLanguage = previousLanguage;
  return translated;
}

function translateTextNode(node) {
  if (!ORIGINAL_TEXT.has(node)) {
    const original = node.nodeValue;
    ORIGINAL_TEXT.set(node, { value: original, language: detectedLanguage(original.trim()) });
  }
  const source = ORIGINAL_TEXT.get(node);
  const original = source.value;
  const trimmed = original.trim();
  if (!trimmed) return;
  const start = original.length - original.trimStart().length;
  const end = original.trimEnd().length;
  const translated = translateFromLanguage(trimmed, source.language, currentLanguage);
  node.nodeValue = `${original.slice(0, start)}${translated}${original.slice(end)}`;
}

function applyTranslations(root = document.body) {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }

  const elements = root.nodeType === Node.ELEMENT_NODE
    ? [root, ...root.querySelectorAll("*")]
    : [...root.querySelectorAll("*")];
  for (const element of elements) {
    for (const attribute of ["placeholder", "aria-label", "title", "alt"]) {
      if (element.hasAttribute(attribute)) {
        let originals = ORIGINAL_ATTRIBUTES.get(element);
        if (!originals) {
          originals = new Map();
          ORIGINAL_ATTRIBUTES.set(element, originals);
        }
        if (!originals.has(attribute)) {
          const value = element.getAttribute(attribute);
          originals.set(attribute, { value, language: detectedLanguage(value) });
        }
        const source = originals.get(attribute);
        element.setAttribute(attribute, translateFromLanguage(source.value, source.language, currentLanguage));
      }
    }
  }

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) translateTextNode(node);
}

function updateLanguageControl() {
  const button = document.querySelector("#language-toggle");
  const flag = document.querySelector("#language-flag");
  const code = document.querySelector("#language-code");
  if (!button || !flag || !code) return;

  const english = currentLanguage === "en";
  flag.className = `language-flag ${english ? "flag-usa" : "flag-spain"}`;
  code.textContent = english ? "EN" : "ES";
  button.setAttribute("aria-label", english ? "Change language to Spanish" : "Cambiar idioma a inglés");
  button.title = english ? "Español" : "English";
  button.setAttribute("aria-pressed", String(english));
}

function setSiteLanguage(language) {
  currentLanguage = language === "en" ? "en" : "es";
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, currentLanguage);
  } catch {
    // The language toggle still works for this page if storage is unavailable.
  }

  updateDocumentLanguage();

  applyTranslations(document.body);
  updateLanguageControl();
  if (typeof renderCatalog === "function") renderCatalog();
  if (typeof renderCart === "function") renderCart();
  const productDialog = document.querySelector("#product-dialog");
  if (productDialog?.open && typeof openProduct === "function") {
    openProduct(productDialog.dataset.productId, Number(productDialog.dataset.variantIndex), "next", false);
  }
  if (document.querySelector("#checkout-dialog")?.open && typeof renderCheckoutItems === "function") {
    renderCheckoutItems();
  }
  if (typeof updateCheckoutTotals === "function" && document.querySelector("#checkout-dialog")?.open) updateCheckoutTotals();
  applyTranslations(document.body);
  updateLanguageControl();
}

document.addEventListener("click", event => {
  if (!event.target.closest("#language-toggle")) return;
  setSiteLanguage(currentLanguage === "es" ? "en" : "es");
});

updateDocumentLanguage();
applyTranslations(document.body);
updateLanguageControl();
new MutationObserver(records => {
  for (const record of records) {
    for (const node of record.addedNodes) applyTranslations(node);
  }
}).observe(document.body, { childList: true, subtree: true });
